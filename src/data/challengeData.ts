/**
 * Shuffles an array using Fisher-Yates algorithm
 */
function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Returns a randomized subset of test questions, with shuffled options.
 * Ensures the options across Gujarati, Hindi, and English stay synchronized in order.
 */
export function getRandomChallengeQuestions(
  count: number = 5,
  ageGroup: string = 'all'
): TestQuestion[] {
  let pool = TEST_QUESTIONS;
  if (ageGroup === '2-4') {
    const easy = TEST_QUESTIONS.filter((q) => q.ageGroup === '2-4' || q.ageGroup === 'all');
    if (easy.length >= count) pool = easy;
  } else if (ageGroup === '4-6') {
    const mid = TEST_QUESTIONS.filter((q) => q.ageGroup === '4-6' || q.ageGroup === '2-4' || q.ageGroup === 'all');
    if (mid.length >= count) pool = mid;
  } else if (ageGroup === '6-8') {
    const adv = TEST_QUESTIONS.filter((q) => q.ageGroup === '6-8' || q.ageGroup === '4-6');
    if (adv.length >= count) pool = adv;
  }

  // Shuffle selected questions pool
  const shuffledQuestions = shuffleArray(pool);
  const selected = shuffledQuestions.slice(0, Math.min(count, shuffledQuestions.length));

  // Shuffle options synchronously for each question so answers are randomized in position
  return selected.map((q) => {
    const optIndices = shuffleArray(q.optionsEn.map((_, idx) => idx));

    return {
      ...q,
      optionsGu: optIndices.map((i) => q.optionsGu[i]),
      optionsHi: optIndices.map((i) => q.optionsHi[i]),
      optionsEn: optIndices.map((i) => q.optionsEn[i]),
    };
  });
}
