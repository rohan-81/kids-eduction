// Helper function to find animal sound info from title or keyword
export function getAnimalSoundInfo(keyword: string): AnimalSoundDetail | null {
  const lower = (keyword || '').toLowerCase();

  // 1. Direct alias check
  for (const [alias, soundKey] of Object.entries(ANIMAL_SOUND_ALIASES)) {
    if (lower.includes(alias.toLowerCase()) && ANIMAL_SOUNDS_DATA[soundKey]) {
      return ANIMAL_SOUNDS_DATA[soundKey];
    }
  }

  // 2. Iterate through canonical data records
  for (const key of Object.keys(ANIMAL_SOUNDS_DATA)) {
    const item = ANIMAL_SOUNDS_DATA[key];
    if (
      lower.includes(key) ||
      lower.includes(item.id) ||
      lower.includes(item.soundKey) ||
      lower.includes(item.nameEn.toLowerCase()) ||
      lower.includes(item.nameGu.toLowerCase()) ||
      lower.includes(item.nameHi.toLowerCase())
    ) {
      return item;
    }
  }
  return null;
}

// Helper to get phonics prompt for a letter
export function getPhonicsPrompt(symbol: string, lang: AppLanguage): { text: string; phoneme: string; emoji: string } | null {
  if (!symbol) return null;
  const trimmed = symbol.trim();
  const upper = trimmed.toUpperCase();

  // English letters A-Z
  if (/^[A-Z]$/.test(upper)) {
    const info = ENGLISH_PHONICS[upper];
    if (info) {
      if (lang === 'gu') {
        return { text: info.promptGu, phoneme: info.phoneme, emoji: info.emoji };
      }
      if (lang === 'hi') {
        return { text: info.promptHi, phoneme: info.phoneme, emoji: info.emoji };
      }
      return { text: info.promptEn, phoneme: info.phoneme, emoji: info.emoji };
    }
  }

  // Gujarati letters (ક થી જ્ઞ, સ્વર અને વ્યંજન)
  if (/^[\u0A85-\u0AB9\u0AE0-\u0AE1\u0A95-\u0AA8\u0AAA-\u0AB0\u0AB2-\u0AB3\u0AB5-\u0AB9\u0A95\u0ACD\u0AB7\u0A9C\u0ACD\u0A9E]+$/.test(trimmed) && trimmed.length <= 4) {
    if (lang === 'gu') {
      return { text: `${trimmed} ... ${trimmed} નો ઉચ્ચાર`, phoneme: `/${trimmed}/`, emoji: '🔤' };
    }
    if (lang === 'hi') {
      return { text: `${trimmed} ... ${trimmed} का उच्चारण`, phoneme: `/${trimmed}/`, emoji: '🔤' };
    }
    return { text: `Letter ${trimmed} sound: /${trimmed}/`, phoneme: `/${trimmed}/`, emoji: '🔤' };
  }

  // Hindi letters (क से ज्ञ, स्वर और व्यंजन)
  if (/^[\u0904-\u0939\u0960-\u0961\u0915-\u0928\u092A-\u0930\u0932-\u0939\u0915\u094D\u0937\u0924\u094D\u0930\u091C\u094D\u091E]+$/.test(trimmed) && trimmed.length <= 4) {
    if (lang === 'gu') {
      return { text: `${trimmed} ... ${trimmed} નો ઉચ્ચાર`, phoneme: `/${trimmed}/`, emoji: '🔤' };
    }
    if (lang === 'hi') {
      return { text: `${trimmed} ... ${trimmed} का उच्चारण`, phoneme: `/${trimmed}/`, emoji: '🔤' };
    }
    return { text: `Letter ${trimmed} sound: /${trimmed}/`, phoneme: `/${trimmed}/`, emoji: '🔤' };
  }

  return null;
}
